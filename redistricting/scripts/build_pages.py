"""Package the saved atlas for GitHub Pages without rerunning any model.

The deployment contains the webapp, its saved browser datasets,. Raw inputs and optimization runs stay outside it.
"""
from __future__ import annotations

import hashlib
import json
import re
import shutil
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "_site"
WEBAPP = ROOT / "redistricting/webapp"
BROWSER = ROOT / "redistricting/export/browser"
SNAPSHOTS = (
    "current-assembly.js", "election-2024.js",
    "hemicycle-layout.js", "projection-2026.js", "partisan-scenarios.js",
)


class References(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.references: list[str] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self.references.extend(value for name, value in attrs
                               if name in {"src", "href"} and value)


def build() -> Path:
    marker = OUTPUT / ".gerard-pages-build"
    if OUTPUT.exists():
        if not marker.is_file():
            raise RuntimeError(f"Refusing to replace an unrecognized directory: {OUTPUT}")
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir()
    marker.write_text("Generated by redistricting/scripts/build_pages.py\n")
    for name in ("index.html", "method.html", "scenarios.html", "atlas.css", "atlas.js", "method.js", "scenarios.css", "scenarios.js"):
        content = (WEBAPP / name).read_text(encoding="utf-8")
        # Paths must remain inside the GitHub Pages repository prefix.
        content = content.replace("const DATA='../export/';", "const DATA='export/';")
        content = content.replace('src="../export/', 'src="export/')
        content = content.replace('href="../src/', 'href="source/')
        (OUTPUT / name).write_text(content, encoding="utf-8")
    shutil.copytree(WEBAPP / "vendor", OUTPUT / "vendor")
    for name in SNAPSHOTS:
        target = OUTPUT / "export/browser" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(BROWSER / name, target)
    for name in ("sample/recom.py", "optimize/sa.py", "sources.py"):
        target = OUTPUT / "source/redistrict" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / "redistricting/src/redistrict" / name, target)
    (OUTPUT / ".nojekyll").touch()

    for page in OUTPUT.glob("*.html"):
        parser = References()
        parser.feed(page.read_text(encoding="utf-8"))
        for ref in parser.references:
            parsed = urlsplit(ref)
            if parsed.scheme or parsed.netloc or not parsed.path:
                continue
            if parsed.path.startswith("/"):
                raise ValueError(f"A root-relative URL would escape the project site: {ref}")
            destination = (page.parent / unquote(parsed.path)).resolve()
            if not destination.is_relative_to(OUTPUT) or not destination.exists():
                raise ValueError(f"Broken local reference in {page.name}: {ref}")

    atlas = (OUTPUT / "atlas.js").read_text(encoding="utf-8")
    if "const DATA='export/';" not in atlas:
        raise ValueError("The browser data URL was not adapted to the Pages root")
    if re.search(r'(?:src|href)=[\'"]\.\./', "".join(
            page.read_text(encoding="utf-8") for page in OUTPUT.glob("*.html"))):
        raise ValueError("Deployment HTML still refers to files outside the site root")

    paths = sorted(path for path in OUTPUT.rglob("*") if path.is_file())
    # These control files belong in the artifact, but are not public URLs.
    # In particular, Pages may return 404 for the .nojekyll marker.
    controls = {marker, OUTPUT / ".nojekyll"}
    manifest = {str(path.relative_to(OUTPUT)): hashlib.sha256(path.read_bytes()).hexdigest()
                for path in paths if path not in controls}
    (OUTPUT / "build-manifest.json").write_text(
        json.dumps({"sha256": manifest}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8")
    size = sum(path.stat().st_size for path in paths)
    print(f"GitHub Pages build: {len(manifest)} files, {size / 1024 / 1024:.1f} MiB")
    print(OUTPUT)
    return OUTPUT


if __name__ == "__main__":
    build()
